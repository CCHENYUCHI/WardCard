/**
 * The check.mjs a batch agent runs (`node ../check.mjs`) to test its output.json: the same rules as the local
 * check (geminiEntries.checkEntryWith + validate.validateEntry), serialized into one dependency-free script with
 * this batch's fact info baked in, so the agent cannot change what it is checked against.
 */
const { normalizeWord } = require('../../cardUtils');
const { lexiconKey } = require('../../lexicon');
const { validateEntry, POS, ARTICLES, CONFIDENCE, WRITERS, MAX } = require('./validate');
const { checkEntryWith, checkAnswerWith, SIMPLIFIED, ZH_FIELDS, stripMarks, ancestorKey, hasSimplified } = require('./geminiEntries');

const MAIN = `
import fs from 'node:fs';

const file = process.argv[2] || 'output.json';
let entries;
try {
  const text = fs.readFileSync(file, 'utf8');
  entries = JSON.parse(text.slice(text.indexOf('['), text.lastIndexOf(']') + 1));
  if (!Array.isArray(entries)) throw new Error('not a JSON array');
} catch (err) {
  console.log(\`\${file}: cannot read a JSON array (\${err.message}). Write the entries as one JSON array.\`);
  process.exit(1);
}
// { "word": "...", "skip": "reason" } marks a word that is a name, place, English word or fragment: not written
const skipped = new Set(entries.filter(e => e && e.skip && e.word).map(e => lexiconKey(e.word)));
const results = checkAnswerWith(entries.filter(e => e && !e.skip), INFOS.filter(i => !skipped.has(lexiconKey(i.lemma))));
const asked = new Set(INFOS.map(i => lexiconKey(i.lemma)));
const extra = entries.filter(e => e && !asked.has(lexiconKey(e.word))).map(e => e.word);
let bad = 0;
for (const [word, { errors }] of Object.entries(results)) {
  if (!errors.length) continue;
  bad++;
  console.log(\`✗ \${word}: \${errors.join('; ')}\`);
}
if (extra.length) console.log(\`✗ words that were not asked for (remove them): \${extra.join(', ')}\`);
console.log(\`\${INFOS.length - skipped.size - bad}/\${INFOS.length - skipped.size} entries OK, \${skipped.size} skipped\${bad || extra.length ? '' : ' — all done'}\`);
process.exit(bad || extra.length ? 1 : 0);
`;

/** check.mjs source for a batch, given factInfo() of each word to write */
function buildCheckScript(infos) {
  return [
    '// Generated by WardCard server/scripts/lexicon/batchCheck.js: checks output.json against this batch\'s facts.',
    `const INFOS = ${JSON.stringify(infos)};`,
    `const POS = ${JSON.stringify(POS)};`,
    `const ARTICLES = ${JSON.stringify(ARTICLES)};`,
    `const CONFIDENCE = ${JSON.stringify(CONFIDENCE)};`,
    `const WRITERS = ${JSON.stringify(WRITERS)};`,
    `const MAX = ${JSON.stringify(MAX)};`,
    `const SIMPLIFIED = new Set(${JSON.stringify([...SIMPLIFIED])});`,
    `const ZH_FIELDS = ${JSON.stringify(ZH_FIELDS)};`,
    'const isStr = (v) => typeof v === \'string\';',
    normalizeWord.toString(),
    `const lexiconKey = ${lexiconKey.toString()};`,
    `const stripMarks = ${stripMarks.toString()};`,
    `const ancestorKey = ${ancestorKey.toString()};`,
    `const hasSimplified = ${hasSimplified.toString()};`,
    validateEntry.toString(),
    checkEntryWith.toString(),
    checkAnswerWith.toString(),
    MAIN
  ].join('\n');
}

module.exports = { buildCheckScript };
